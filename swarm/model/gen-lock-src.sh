#!/bin/sh
# Regenerates SwarmModel/LockSrc.lean: locks.lua and util.lua as syntax trees (`lua-lean dump`).
# `gen-lock-src.sh --check` fails if the committed file is not what the sources give now (replay.sh runs it).
here=$(cd "$(dirname "$0")" && pwd)
lua=$here/../lua/swarm
out=$(mktemp) || exit 1
trap 'rm -f "$out"' EXIT
{
  printf 'import LuaLean.Syntax\n\n/-! GENERATED by gen-lock-src.sh from swarm/lua/swarm/locks.lua and util.lua: do not edit. -/\n\nnamespace Swarm\nopen Lua\n\n'
  "$here/../../lua-lean/lua-lean" dump Locks "$lua/locks.lua" Util "$lua/util.lua" || exit 1
  printf 'end Swarm\n'
} >"$out" || exit 1
if [ "$1" = --check ]; then cmp -s "$out" "$here/SwarmModel/LockSrc.lean" || { echo "SwarmModel/LockSrc.lean is stale: run swarm/model/gen-lock-src.sh" >&2; exit 1; }
else cp "$out" "$here/SwarmModel/LockSrc.lean"; fi
