#!/bin/sh
# Regenerates SwarmModel/LockSrc.lean: locks.lua and util.lua as syntax trees, which LockProof.lean is about.
# `gen-lock-src.sh --check` fails if the committed file is not what the sources give now (replay.sh runs it).
here=$(cd "$(dirname "$0")" && pwd)
lua=$here/../lua/swarm
out=$(mktemp) || exit 1
trap 'rm -f "$out"' EXIT
{
  printf 'import SwarmModel.Lua.Syntax\n\n/-! GENERATED by gen-lock-src.sh from swarm/lua/swarm/locks.lua and util.lua: do not edit. -/\n\nnamespace Swarm.Lua\n\n'
  cd "$here" && { if command -v lake >/dev/null; then lake env lean --run SwarmModel/LuaDump.lean Locks "$lua/locks.lua" Util "$lua/util.lua"
    else nix shell nixpkgs#elan -c lake env lean --run SwarmModel/LuaDump.lean Locks "$lua/locks.lua" Util "$lua/util.lua"; fi; } || exit 1
  printf 'end Swarm.Lua\n'
} >"$out" || exit 1
if [ "$1" = --check ]; then cmp -s "$out" "$here/SwarmModel/LockSrc.lean" || { echo "SwarmModel/LockSrc.lean is stale: run swarm/model/gen-lock-src.sh" >&2; exit 1; }
else cp "$out" "$here/SwarmModel/LockSrc.lean"; fi
