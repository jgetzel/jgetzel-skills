create table cust(id integer primary key, name text, region text);
create table ord(id integer primary key, cid integer, day integer, total real);
create table item(oid integer, sku text, qty integer, price real);
create index ord_cid on ord(cid);
create index item_oid on item(oid);
create index item_sku on item(sku);
