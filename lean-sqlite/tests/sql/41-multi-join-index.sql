select c.name, o.id, i.sku, i.qty from cust c join ord o on o.cid = c.id join item i on i.oid = o.id order by c.name, o.id, i.sku;
select c.name, sum(i.qty * i.price) from cust c join ord o on o.cid = c.id join item i on i.oid = o.id group by c.id order by c.name;
select c.name, count(i.sku) from cust c left join ord o on o.cid = c.id left join item i on i.oid = o.id group by c.id order by c.id;
select o.id, count(i.sku) n from ord o left join item i on i.oid = o.id group by o.id order by o.id;
select i.sku, count(distinct o.cid) from item i join ord o on o.id = i.oid group by i.sku order by i.sku;
select c.region, count(*), sum(i.qty) from cust c join ord o on o.cid = c.id join item i on i.oid = o.id group by c.region order by c.region;
select c.name from cust c where c.id in (select cid from ord where id in (select oid from item where sku = 'a')) order by c.name;
select o.id from ord o where not exists (select 1 from item i where i.oid = o.id) order by o.id;
