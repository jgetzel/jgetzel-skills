create table big(id integer primary key, n integer, s text, r real);
with recursive c(i) as (select 1 union all select i+1 from c where i < 20000) insert into big select i, i % 97, 'row-' || i, i / 7.0 from c;
select count(*), sum(n), min(id), max(id), sum(r) from big;
