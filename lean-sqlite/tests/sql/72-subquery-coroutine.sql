-- A FROM subquery or WITH table yields its rows as the outer query reads them (sqlite's co-routine): a row past the
-- outer LIMIT is never computed, so an error in it is never raised. Some shapes are still computed whole first.
CREATE TABLE m(a INTEGER PRIMARY KEY, b INTEGER);
INSERT INTO m VALUES(1, -9223372036854775808),(2,5),(3,6);
CREATE TABLE t(k INTEGER PRIMARY KEY, v TEXT);
INSERT INTO t VALUES(1,'x'),(2,'y'),(3,'z');
