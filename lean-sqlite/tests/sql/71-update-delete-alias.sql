-- UPDATE and DELETE name their table by its alias in SET and WHERE (not in RETURNING, which keeps the table's own name)
create table t1(a integer primary key, b); insert into t1 values(1,1),(6,2),(7,3);
create table w(a, b, primary key(a)) without rowid; insert into w values(1,1),(6,2),(7,3);
update t1 as q set b = b + 100 where q.a = 6; select * from t1 order by a;
update t1 as q set b = q.b + 100 where q.a = 6 returning q.a, q.b, b, a; select * from t1 order by a;
update t1 as q set b = t1.b + 1 where a = 6;
update t1 as q set b = 1 where t1.a = 6;
update t1 as q set b = 1 returning t1.a;
update t1 q set b = 1 where q.a = 6; select * from t1 order by a;
update t1 as q set b = (select count(*) from t1 where t1.a > q.a) where q.a < 8; select * from t1 order by a;
delete from t1 as q where q.a = 6 returning q.a, a; select count(*) from t1;
delete from t1 q where q.a = 6; select count(*) from t1;
delete from t1 as q where t1.a = 6;
delete from t1 as q returning q.*;
