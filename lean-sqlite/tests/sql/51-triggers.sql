create table t(id integer primary key, a int, b text);
create table log(ev text, x, y);
create trigger t_ai after insert on t begin insert into log values('ins', new.id, new.a); end;
create trigger t_bu before update of a on t when new.a > old.a begin insert into log values('up', old.a, new.a); end;
create trigger t_ad after delete on t for each row begin insert into log values('del', old.id, old.b); end;
insert into t values(1, 10, 'x'), (2, 20, 'y');
