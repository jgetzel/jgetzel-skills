-- an UPDATE or DELETE reads its row again after its BEFORE triggers: the columns it does not set are as they left them, and a row they deleted is skipped
create table t(a integer primary key, b, d); create index tb on t(b);
insert into t values(1,5,0),(2,6,0);
create trigger bu before update of d on t begin update t set b = 999 where a = old.a; end;
update t set d = 1 where a = 1; select * from t; select changes();
update t set d = 2, b = 7 where a = 2; select * from t; select changes();
select a from t where b = 999; select a from t where b = 5;
drop trigger bu;
create trigger bu2 before update on t begin delete from t where a = old.a; end;
update t set d = 9; select * from t; select changes(); select count(*) from t where b = 999;
drop trigger bu2;
insert into t values(3,1,0),(4,2,0);
create table log(x);
create trigger au after update on t begin insert into log values('au ' || old.a || ' ' || new.b); end;
create trigger bu3 before update on t begin update t set b = b + 100 where a = old.a; end;
update t set d = 5 where a = 3; select * from t order by a; select * from log; select a from t where b = 101;
drop trigger au; drop trigger bu3;
create trigger bd before delete on t begin delete from t where a = old.a; end;
create trigger ad after delete on t begin insert into log values('ad ' || old.a); end;
delete from t where a >= 3; select * from t order by a; select changes(); select * from log;
drop trigger bd;
create trigger bd2 before delete on t begin delete from t where a = old.a + 1; end;
delete from t; select * from t; select changes(); select * from log;
create table w(k primary key, b, d) without rowid; create index wb on w(b);
insert into w values(1,5,0),(2,6,0);
create trigger wbu before update of d on w begin update w set b = 999 where k = old.k; end;
update w set d = 1 where k = 1; select * from w order by k; select changes(); select k from w where b = 999;
create trigger wbd before delete on w begin delete from w where k = old.k; end;
delete from w; select * from w order by k; select changes();
