create table c(id integer primary key, name text);
create table o(id integer primary key, cid integer, amt integer);
insert into c values(1,'ann'),(2,'ben'),(3,'cat'),(4,'dan');
insert into o values(10,1,100),(11,1,50),(12,2,75),(13,5,20),(14,null,5);
select c.name, o.amt from c join o on c.id = o.cid order by c.name, o.amt;
select c.name, o.amt from c inner join o on o.cid = c.id order by o.id;
select c.name, o.amt from c left join o on c.id = o.cid order by c.id, o.id;
select c.name, o.amt from c left outer join o on c.id = o.cid and o.amt > 60 order by c.id, o.id;
select c.name, o.id from c left join o on c.id = o.cid where o.id is null order by c.id;
select c.name, o.id from c left join o on c.id = o.cid where o.amt > 60 order by c.id;
select count(*) from c, o;
select c.id, o.id from c, o where c.id = o.cid order by 1, 2;
select c.name, sum(o.amt) from c left join o on c.id = o.cid group by c.id order by c.id;
select * from c cross join o where c.id = 1 and o.id < 12 order by o.id;
create table c2(id integer, extra text);
insert into c2 values(1,'one'),(2,'two'),(9,'nine');
select * from c join c2 using(id) order by id;
select * from c left join c2 using(id) order by c.id;
select * from c natural join c2 order by id;
select a.name, b.name from c a join c b on a.id < b.id order by 1, 2;
select a.name, b.name from c a join c b on a.id + 1 = b.id order by 1;
select c.name, o.amt, c2.extra from c join o on c.id = o.cid left join c2 on c2.id = c.id order by o.id;
select x.name from (select * from c where id > 2) x join o on 1 order by x.name, o.id limit 4;
select * from c right join o on c.id = o.cid order by o.id;
select * from c full join o on c.id = o.cid order by c.id, o.id;
