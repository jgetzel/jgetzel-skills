-- a default read for a row older than the ALTER goes through the column's affinity, as a stored value does
create table t(a);
insert into t values (1), (2);
alter table t add column f real default 1;
alter table t add column i integer default '5';
alter table t add column i2 integer default 2.0;
alter table t add column n numeric default '7.0';
alter table t add column n2 numeric default 'abc';
alter table t add column x text default 12;
alter table t add column x2 text default 1.5;
alter table t add column b blob default 3;
alter table t add column u default 4;
alter table t add column r2 real default '2.5';
alter table t add column r3 real default 'zz';
alter table t add column neg real default -3;
alter table t add column bl blob default x'0102';
alter table t add column nul real;
select a, f, typeof(f), i, typeof(i), i2, typeof(i2), n, typeof(n), n2, typeof(n2) from t;
select a, x, typeof(x), x2, typeof(x2), b, typeof(b), u, typeof(u), r2, typeof(r2), r3, typeof(r3) from t;
select a, neg, typeof(neg), hex(bl), typeof(bl), nul, typeof(nul) from t;
insert into t(a) values (3);
insert into t(a, f, i, x) values (4, 9, '8', 9);
select a, f, typeof(f), i, typeof(i), n, typeof(n), x, typeof(x), neg, typeof(neg) from t order by a;
select * from t order by a;
update t set a = a + 10 where a = 1;
select a, f, typeof(f), x, typeof(x) from t order by a;
update t set f = f + 1 where a = 2;
select a, f, typeof(f) from t order by a;
select f = 1, f = 1.0, f < 2, typeof(f + 0), f * 2 from t where a = 12;
create index tf on t(f);
select a, f, typeof(f) from t where f = 1 order by a;
select a from t where f = 1.0 order by a;
select a, typeof(f) from t order by f, a;
create index tx on t(x, i);
select a, x, typeof(x), i, typeof(i) from t where x = '12' order by a;
select count(*), sum(f), typeof(sum(f)), min(f), typeof(min(f)), max(i), typeof(max(i)) from t;
select distinct typeof(f), f from t order by 1, 2;
select f, count(*) from t group by f order by f;
-- WITHOUT ROWID
create table w(k integer primary key, v) without rowid;
insert into w values (1, 'a'), (2, 'b');
alter table w add column f real default 1;
alter table w add column x text default 5;
select k, v, f, typeof(f), x, typeof(x) from w order by k;
insert into w values (3, 'c', 4, 6);
select k, f, typeof(f), x, typeof(x) from w order by k;
update w set v = 'z' where k = 1;
select k, v, f, typeof(f), x, typeof(x) from w order by k;
-- an INTEGER PRIMARY KEY table and a table with a real column added after rows exist
create table p(id integer primary key, s text);
insert into p values (1, 'one'), (2, 'two');
alter table p add column r real default 0;
alter table p add column q integer default 3.0;
select id, s, r, typeof(r), q, typeof(q) from p;
update p set s = s || '!' where id = 1;
select id, s, r, typeof(r), q, typeof(q) from p;
delete from p where r = 0 and id = 2;
select * from p;
insert into p(id, s, r) select a, 'n', f from t where a < 5;
select id, s, r, typeof(r), q, typeof(q) from p order by id;
-- UPDATE and DELETE read the added column of old rows through its affinity
create table q(id integer primary key, v text);
insert into q values (1, 'a'), (2, 'b'), (3, 'c'), (4, 'd');
alter table q add column f real default 1;
alter table q add column x text default 12;
alter table q add column n integer default '7';
select id from q where f = 1 and x = '12' and n = 7 order by id;
update q set v = v || '!' where f = 1 and typeof(f) = 'real' and typeof(x) = 'text' and typeof(n) = 'integer';
select id, v, f, typeof(f), x, typeof(x), n, typeof(n) from q order by id;
update q set f = f + 1 where id = 1;
update q set v = 'z' where id = 2;
update q set x = x || 'y' where id = 3;
select id, v, f, typeof(f), x, typeof(x), n, typeof(n) from q order by id;
delete from q where f = 1 and x = '12' and id = 4;
select id, v, f, typeof(f), x, typeof(x), n, typeof(n) from q order by id;
